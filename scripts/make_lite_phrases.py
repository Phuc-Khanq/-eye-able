"""Writes the website's in-browser voice vocabulary from the engine's own tables, so lite mode and the engine
understand the same phrases:  python scripts/make_lite_phrases.py   (tests/test_lite_phrases.py checks it is up to date)

Reads engine/voice/commands.py and engine/config.py with ast (nothing is imported or run) and writes
diseyeble-frontend/diseyeble-frontend/js/lite-phrases.js.
"""
from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "diseyeble-frontend" / "diseyeble-frontend" / "js" / "lite-phrases.js"

COMMAND_NAMES = ["FIXED_COMMANDS", "KEY_SHORTCUTS", "ANSWER_MISHEARINGS", "DICTATION_EXIT", "EXACT_ONLY", "FILLER_WORDS",
                 "FILLER_PREFIXES", "TRIGGER_WORDS", "TYPE_VERBS", "TARGET_VERBS", "LABEL_LEADING_WORDS", "POINTING_WORDS",
                 "FIXED_CUTOFF", "VERB_CUTOFF", "EXACT_ONLY_BELOW", "MAX_COMMAND_WORDS", "MAX_LABEL_WORDS"]
CONFIG_NAMES = ["launch_apps", "launch_aliases", "launch_sites", "launch_search_url"]


def literals(path: Path) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name, value = node.target.id, node.value
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name, value = node.targets[0].id, node.value
        else:
            continue
        if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "field":     # dataclass field(default_factory=lambda: {...})
            for kw in value.keywords:
                if kw.arg == "default_factory" and isinstance(kw.value, ast.Lambda):
                    value = kw.value.body
        try:
            found[name] = ast.literal_eval(value)
        except (ValueError, SyntaxError):
            pass
    return found


def build() -> str:
    cmd, cfg = literals(ROOT / "engine/voice/commands.py"), literals(ROOT / "engine/config.py")
    data = {}
    for n in COMMAND_NAMES:
        v = cmd[n]
        data[n] = sorted(v) if isinstance(v, (set, frozenset)) else v
    for n in CONFIG_NAMES:
        data[n] = cfg[n]
    body = json.dumps(data, indent=1, ensure_ascii=False, sort_keys=False)
    return ("/* GENERATED by scripts/make_lite_phrases.py from engine/voice/commands.py and engine/config.py. Do not edit:\n"
            "   change the engine's tables and run the script. Lite mode's voice uses exactly these phrases. */\n"
            f"const DZ_PHRASES = {body};\n"
            "if (typeof window !== 'undefined') window.DZ_PHRASES = DZ_PHRASES;\n"
            "if (typeof module !== 'undefined') module.exports = DZ_PHRASES;\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
